#!/usr/bin/env python3
"""
build_bdc_varlib.py

Builds the BDC Variable Library (BDCVL) LinkML schema from the
priority_variables_transform folder of RTIInternational/NHLBI-BDC-DMC-HV.

Layout
  - One CLASS per BDCHM class found in the specs that identifies a concept:
        Condition               (concept slot: condition_concept)
        MeasurementObservation  (concept slot: observation_type)
        Observation             (concept slot: observation_type)
        SdohObservation         (concept slot: observation_type)
        DrugExposure            (concept slot: drug_concept)
        Procedure               (concept slot: procedure_concept)
    MeasurementObservation entries nested inside MeasurementObservationSet
    (e.g. spirometry) are collected under MeasurementObservation.
  - One SLOT per concept code (e.g. MONDO:0005068 -> mondo_0005068,
    OBA:VT0003179 -> oba_vt0003179). All studies/tables that use that code
    are folded into the same slot as comma-delimited annotations.
  - One MODULE per class (bdc_varlib_<class>.yaml), shared enums in
    bdc_varlib_common.yaml, entry point bdc_varlib.yaml.

Slot fields
  title               concept name: source file name(s), or an ontology label
                      when --labels is given (e.g. afib, hist_cor_angio)
  exact_mappings      [CURIE]
  description         distinct provenance / method strings, joined by '; '
  range               ConditionStatusEnum | shared/minted enum | float | string
  annotations         concept_id (CURIE), concept_name, bdchm_class, source_study, dataset_accession,
                      variable_accession, source_file (all comma-delimited),
                      optional unit

Usage
  python3 build_bdc_varlib.py --repo-dir /path/to/NHLBI-BDC-DMC-HV --outdir src/bdc_varlib/schema
  python3 build_bdc_varlib.py --outdir src/bdc_varlib/schema      # downloads the repo
"""
import argparse
import glob
import os
import re
import sys
import tarfile
import tempfile
import urllib.request
from collections import defaultdict

import yaml
from linkml_runtime.utils.schemaview import SchemaView

REPO_TARBALL_URL = (
    "https://codeload.github.com/RTIInternational/NHLBI-BDC-DMC-HV/tar.gz/refs/heads/main"
)
SOURCE_REPO_URL = (
    "https://github.com/RTIInternational/NHLBI-BDC-DMC-HV/tree/main/priority_variables_transform"
)
GENERATED_MARK = "Auto-generated by build_bdc_varlib.py"

PREFIXES = {
    "linkml": "https://w3id.org/linkml/",
    "bdcvl": "https://w3id.org/bdc/varlib/",
    "bdchm": "https://w3id.org/bdchm/",
    "MONDO": "http://purl.obolibrary.org/obo/MONDO_",
    "OBA": "http://purl.obolibrary.org/obo/OBA_",
    "HP": "http://purl.obolibrary.org/obo/HP_",
    "OMOP": "https://athena.ohdsi.org/search-terms/terms/",
    "RxCUI": "https://mor.nlm.nih.gov/RxNav/search?searchBy=RXCUI&searchTerm=",
    "ATC": "https://www.whocc.no/atc_ddd_index/?code=",
    "NDFRT": "http://purl.bioontology.org/ontology/NDFRT/",
    "VANDF": "http://purl.bioontology.org/ontology/VANDF/",
    "MeSH": "http://id.nlm.nih.gov/mesh/",
    "LOINC": "https://loinc.org/",
    "UCUM": "https://units-of-measurement.org/",
}

# BDCHM class -> slot_derivations key that carries the concept
CONCEPT_SLOT = {
    "Condition": "condition_concept",
    "MeasurementObservation": "observation_type",
    "Observation": "observation_type",
    "SdohObservation": "observation_type",
    "DrugExposure": "drug_concept",
    "Procedure": "procedure_concept",
}
CLASS_ORDER = list(CONCEPT_SLOT)
STATUS_KEYS = ("condition_status", "exposure_status", "procedure_status", "value_enum")

STATUS_VALUES = frozenset({"ABSENT", "PRESENT", "HISTORICAL", "UNKNOWN"})
VOCABS = "MONDO|OMOP|RxCUI|OBA|HP|LOINC|ATC|NDFRT|VANDF|MeSH"
CODE_RE = re.compile(rf"\b(?:{VOCABS}):[\w.\-]+")
CURIE_RE = re.compile(rf"^(?:{VOCABS}):[\w.\-]+$")
PHV_RE = re.compile(r"phv\d+")


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #

def to_pascal_case(text: str) -> str:
    text = re.sub(r"[^a-zA-Z0-9]+", " ", str(text)).strip()
    return "".join(w[:1].upper() + w[1:] for w in text.split())


def to_snake_case(text: str) -> str:
    text = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", str(text))
    text = re.sub(r"[^a-zA-Z0-9]+", "_", text).strip("_")
    return text.lower()


def ordered_dedup(items) -> list:
    seen, out = set(), []
    for x in items:
        if x and x not in seen:
            seen.add(x)
            out.append(x)
    return out


def dump(obj) -> str:
    return yaml.dump(obj, default_flow_style=False) if obj is not None else ""


def fetch_repo(tmp_dir: str) -> str:
    tarball_path = os.path.join(tmp_dir, "repo.tar.gz")
    print(f"Downloading {REPO_TARBALL_URL} ...")
    urllib.request.urlretrieve(REPO_TARBALL_URL, tarball_path)
    with tarfile.open(tarball_path) as tf:
        tf.extractall(tmp_dir)
    (extracted,) = [
        d for d in os.listdir(tmp_dir)
        if d.startswith("NHLBI-BDC-DMC-HV") and os.path.isdir(os.path.join(tmp_dir, d))
    ]
    return os.path.join(tmp_dir, extracted, "priority_variables_transform")


# --------------------------------------------------------------------------- #
# Extraction from one class_derivations body
# --------------------------------------------------------------------------- #

def concept_codes(cls_name: str, slot_derivations: dict) -> list:
    """All concept identifiers for this entry (a case() expr can yield several)."""
    node = slot_derivations.get(CONCEPT_SLOT[cls_name])
    if node is None:
        return []
    text = dump(node)
    codes = ordered_dedup(CODE_RE.findall(text))
    if codes:
        return codes
    if isinstance(node, dict) and isinstance(node.get("value"), str) and node["value"].strip():
        return [node["value"].strip()]     # e.g. EDUCATIONAL_ATTAINMENT
    return []


def find_status(slot_derivations: dict):
    for key in STATUS_KEYS:
        sd = slot_derivations.get(key)
        if isinstance(sd, dict) and sd.get("value_mappings"):
            return sd, sd.get("value_mappings")
    return None, None


def find_quantity(slot_derivations: dict):
    """Returns (quantity slot dict or None, unit)."""
    vq = slot_derivations.get("value_quantity")
    if not isinstance(vq, dict):
        return None, None
    unit = None
    for item in vq.get("class_derivations") or []:
        if not isinstance(item, dict):
            continue
        for _qn, qbody in item.items():
            qsd = (qbody or {}).get("slot_derivations", {}) or {}
            u = qsd.get("unit")
            if isinstance(u, dict) and u.get("value"):
                unit = str(u["value"])
    return vq, unit


def extract_record(cls_name: str, body: dict, study: str, source_file: str) -> list:
    sd = body.get("slot_derivations", {}) or {}
    codes = concept_codes(cls_name, sd)
    status_node, value_mappings = find_status(sd)
    qty_node, unit = find_quantity(sd)

    phv_text = dump(status_node) or dump(qty_node) or dump(sd.get("value_enum"))
    phvs = ordered_dedup(PHV_RE.findall(phv_text))

    prov = None
    for key, node in sd.items():
        if key.endswith("_provenance") and isinstance(node, dict) and node.get("value"):
            prov = str(node["value"])
            break
    method = None
    mt = sd.get("method_type")
    if isinstance(mt, dict) and mt.get("value"):
        method = str(mt["value"])

    return [{
        "code": c, "bdchm_class": cls_name, "study": study, "source_file": source_file,
        "pht": body.get("populated_from"), "phvs": phvs, "unit": unit,
        "provenance": prov, "method": method, "value_mappings": value_mappings,
    } for c in codes]


def walk(class_derivations, study, source_file, out, skipped):
    """Visit class_derivations (dict or list of single-key dicts), recursing into
    nested class_derivations so MeasurementObservationSet members are found."""
    items = []
    if isinstance(class_derivations, dict):
        items = list(class_derivations.items())
    elif isinstance(class_derivations, list):
        for it in class_derivations:
            if isinstance(it, dict):
                items.extend(it.items())
    for cls_name, body in items:
        if not isinstance(body, dict):
            continue
        if cls_name in CONCEPT_SLOT:
            recs = extract_record(cls_name, body, study, source_file)
            if recs:
                out.extend(recs)
            else:
                skipped.append(f"{source_file}:{cls_name}")
        for sub in (body.get("slot_derivations") or {}).values():
            if isinstance(sub, dict) and "class_derivations" in sub:
                walk(sub["class_derivations"], study, source_file, out, skipped)


# --------------------------------------------------------------------------- #
# Slot construction
# --------------------------------------------------------------------------- #

def slot_name_for(code: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", code.lower()).strip("_")


def build_slot(code: str, cls_name: str, records: list, enum_registry: dict, enums: dict,
               labels: dict = None) -> dict:
    studies = ordered_dedup(r["study"] for r in records)
    phts = ordered_dedup(r["pht"] for r in records)
    phvs = ordered_dedup(p for r in records for p in r["phvs"])
    files = ordered_dedup(r["source_file"] for r in records)
    provs = ordered_dedup(r["provenance"] for r in records)
    methods = ordered_dedup(r["method"] for r in records)
    units = ordered_dedup(r["unit"] for r in records)

    if provs:
        description = "; ".join(sorted(provs))
    elif methods:
        description = "; ".join(sorted(methods))
    else:
        description = f"{cls_name} derivation of '{code}'"

    target_union = set()
    for r in records:
        if r["value_mappings"]:
            target_union |= {str(v) for v in r["value_mappings"].values()}

    range_ = "string"
    if target_union:
        if target_union <= STATUS_VALUES:
            range_ = "ConditionStatusEnum"
        else:
            key = frozenset(target_union)
            if key in enum_registry:
                range_ = enum_registry[key]
            else:
                enum_name = to_pascal_case(slot_name_for(code).replace("_", " ")) + "Enum"
                existing = set(enum_registry.values())
                base, n = enum_name, 1
                while enum_name in existing:
                    n += 1
                    enum_name = f"{base}{n}"
                enum_registry[key] = enum_name
                enums[enum_name] = {
                    "description": f"Coded values observed for '{code}' across contributing studies.",
                    "permissible_values": {
                        v: ({"meaning": v} if CURIE_RE.match(v) else None)
                        for v in sorted(target_union)
                    },
                }
                range_ = enum_name
    elif units:
        range_ = "float"

    # human-readable name: ontology label if supplied via --labels, otherwise the
    # source concept file name(s) (e.g. afib, hist_cor_angio)
    file_names = ordered_dedup(os.path.basename(f)[: -len(".yaml")] for f in files)
    label = (labels or {}).get(code)
    name = label if label else ", ".join(file_names)

    annotations = {
        "concept_id": code,
        "concept_name": name,
        "bdchm_class": cls_name,
        "source_study": ", ".join(studies),
        "dataset_accession": ", ".join(phts),
        "variable_accession": ", ".join(phvs) if phvs else "(derived via expr; see source_file)",
        "source_file": ", ".join(files),
    }
    if units:
        annotations["unit"] = ", ".join(units)

    slot_def = {"title": name, "description": description, "range": range_,
                "annotations": annotations}
    if CURIE_RE.match(code):
        slot_def["exact_mappings"] = [code]
    if len(units) == 1:
        slot_def["unit"] = {"ucum_code": units[0]}
    return slot_def


# --------------------------------------------------------------------------- #
# Build
# --------------------------------------------------------------------------- #

def write_yaml(path: str, header: str, data: dict):
    with open(path, "w") as fh:
        fh.write(f"# {header}\n# {GENERATED_MARK}\n")
        yaml.dump(data, fh, sort_keys=False, width=100, allow_unicode=True)


def clean_previous(outdir: str):
    """Remove files this script wrote on an earlier run (e.g. the old category modules)."""
    for p in glob.glob(os.path.join(outdir, "bdc_varlib*.yaml")):
        with open(p) as fh:
            head = fh.read(400)
        if GENERATED_MARK in head:
            os.remove(p)
            print(f"  removed previous {os.path.basename(p)}")


def build(transform_dir: str, outdir: str, labels: dict = None):
    study_dirs = sorted(d for d in os.listdir(transform_dir)
                        if d.endswith("-ingest") and os.path.isdir(os.path.join(transform_dir, d)))
    print(f"Found {len(study_dirs)} study folders: {study_dirs}")

    # class -> code -> [records]
    by_class = {c: defaultdict(list) for c in CLASS_ORDER}
    skipped = []

    for study_dir in study_dirs:
        study = study_dir[: -len("-ingest")]
        full_dir = os.path.join(transform_dir, study_dir)
        for fname in sorted(f for f in os.listdir(full_dir) if f.endswith(".yaml")):
            fpath = os.path.join(full_dir, fname)
            try:
                with open(fpath) as fh:
                    content = yaml.safe_load(fh)
            except yaml.YAMLError as e:
                print(f"  ! failed to parse {fpath}: {e}", file=sys.stderr)
                continue
            if isinstance(content, dict):
                content = [content]
            if not isinstance(content, list):
                continue
            recs = []
            for entry in content:
                if isinstance(entry, dict) and "class_derivations" in entry:
                    walk(entry["class_derivations"], study, f"{study_dir}/{fname}", recs, skipped)
            for r in recs:
                by_class[r["bdchm_class"]][r["code"]].append(r)

    # slot names are global in LinkML: if one code is used by several classes,
    # suffix the class name so the slots stay distinct
    code_classes = defaultdict(set)
    for cls_name, codes in by_class.items():
        for code in codes:
            code_classes[code].add(cls_name)

    enum_registry, minted = {}, {}
    class_slots = {}
    for cls_name in CLASS_ORDER:
        slots = {}
        for code, records in sorted(by_class[cls_name].items()):
            name = slot_name_for(code)
            if len(code_classes[code]) > 1:
                name = f"{name}_{to_snake_case(cls_name)}"
            slots[name] = build_slot(code, cls_name, records, enum_registry, minted, labels)
        class_slots[cls_name] = slots

    os.makedirs(outdir, exist_ok=True)
    clean_previous(outdir)

    common_enums = {
        "ConditionStatusEnum": {
            "description": "Status vocabulary used by Condition, DrugExposure and Procedure derivations.",
            "permissible_values": {
                "ABSENT": {"description": "Reported absent."},
                "PRESENT": {"description": "Reported present."},
                "HISTORICAL": {"description": "Present historically, not currently."},
                "UNKNOWN": {"description": "Not known / not reported."},
            },
        }
    }
    common_enums.update(minted)
    write_yaml(os.path.join(outdir, "bdc_varlib_common.yaml"), "BDC Variable Library: shared enums/prefixes", {
        "id": "https://w3id.org/bdc/varlib/common",
        "name": "bdc_varlib_common",
        "title": "BDC Variable Library: Common",
        "description": ("Shared enums and prefixes. All enums live here so every class module "
                        f"is loadable on its own. Source: {SOURCE_REPO_URL}"),
        "license": "Apache-2.0",
        "prefixes": PREFIXES,
        "default_prefix": "bdcvl",
        "default_range": "string",
        "imports": ["linkml:types"],
        "enums": common_enums,
    })
    print(f"  wrote bdc_varlib_common.yaml: {len(common_enums)} enums")

    module_names, summaries = [], []
    for cls_name in CLASS_ORDER:
        slots = class_slots[cls_name]
        module = f"bdc_varlib_{to_snake_case(cls_name)}"
        write_yaml(os.path.join(outdir, f"{module}.yaml"), f"BDC Variable Library: {cls_name}", {
            "id": f"https://w3id.org/bdc/varlib/{to_snake_case(cls_name)}",
            "name": module,
            "title": f"BDC Variable Library: {cls_name}",
            "description": (f"One slot per concept code used by BDCHM {cls_name} derivations in "
                            f"{SOURCE_REPO_URL} (concept slot: {CONCEPT_SLOT[cls_name]}). "
                            "Contributing studies, tables and variables are recorded as "
                            "comma-delimited annotations on each slot."),
            "license": "Apache-2.0",
            "prefixes": PREFIXES,
            "default_prefix": "bdcvl",
            "default_range": "string",
            "imports": ["linkml:types", "bdc_varlib_common"],
            "classes": {cls_name: {
                "description": f"Concepts derived as BDCHM {cls_name}.",
                "slots": sorted(slots),
            }},
            "slots": slots,
        })
        module_names.append(module)
        summaries.append((cls_name, module, len(slots)))
        print(f"  wrote {module}.yaml: class {cls_name}, {len(slots)} slots")

    write_yaml(os.path.join(outdir, "bdc_varlib.yaml"), "BDC Variable Library: umbrella schema (entry point)", {
        "id": "https://w3id.org/bdc/varlib",
        "name": "bdc_varlib",
        "title": "BDC Variable Library",
        "description": (f"LinkML variable library for BioData Catalyst, generated from {SOURCE_REPO_URL}.\n\n"
                        "Modules:\n" + "\n".join(f"  - {m}.yaml   {c} ({n} concepts)"
                                                  for c, m, n in summaries)),
        "license": "Apache-2.0",
        "see_also": [SOURCE_REPO_URL],
        "prefixes": PREFIXES,
        "default_prefix": "bdcvl",
        "default_range": "string",
        "imports": ["linkml:types", "bdc_varlib_common"] + module_names,
    })
    print(f"  wrote bdc_varlib.yaml: {len(module_names)} modules, "
          f"{sum(n for _, _, n in summaries)} slots")

    if skipped:
        with open(os.path.join(outdir, "skipped.txt"), "w") as fh:
            fh.write("\n".join(sorted(set(skipped))) + "\n")
        print(f"  WARNING: {len(set(skipped))} entries had no concept code -> skipped.txt")


def validate(outdir: str):
    sv = SchemaView(os.path.join(outdir, "bdc_varlib.yaml"))
    print(f"\nSchemaView: {len(sv.all_classes())} classes, {len(sv.all_slots())} slots, "
          f"{len(sv.all_enums())} enums")


def main_cli():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-dir", default=None, help="local clone of NHLBI-BDC-DMC-HV (optional)")
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--labels", default=None,
                    help="optional TSV (CURIE<TAB>label) to use ontology labels as slot names")
    args = ap.parse_args()

    labels = {}
    if args.labels:
        with open(args.labels) as fh:
            for line in fh:
                parts = line.rstrip("\n").split("\t")
                if len(parts) >= 2 and parts[0] and parts[1]:
                    labels[parts[0].strip()] = parts[1].strip()

    if args.repo_dir:
        tdir = os.path.join(args.repo_dir, "priority_variables_transform")
        build(tdir if os.path.isdir(tdir) else args.repo_dir, args.outdir, labels)
    else:
        with tempfile.TemporaryDirectory() as tmp:
            build(fetch_repo(tmp), args.outdir, labels)
    validate(args.outdir)


if __name__ == "__main__":
    main_cli()
